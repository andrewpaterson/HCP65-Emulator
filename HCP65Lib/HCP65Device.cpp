#include "HCP65Device.h"


//////////////////////////////////////////////////////////////////////////
//
// uiMinimumSlotSize is HCP65_LARGE_SLOT_SIZE for a device that decodes A16.
//
//////////////////////////////////////////////////////////////////////////
void CHCP65Device::Init(uint32 uiMinimumSlotSize)
{
	mpcHCP65 = NULL;
	muiMinimumSlotSize = uiMinimumSlotSize;
	mbHeldInReset = true;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CHCP65Device::Kill(void)
{
	mpcHCP65 = NULL;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CHCP65Device::Attach(CHCP65* pcHCP65)
{
	mpcHCP65 = pcHCP65;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint32 CHCP65Device::GetMinimumSlotSize(void)
{
	return muiMinimumSlotSize;
}


//////////////////////////////////////////////////////////////////////////
//
// The system reset.
//
//////////////////////////////////////////////////////////////////////////
void CHCP65Device::Reset(void)
{
}


//////////////////////////////////////////////////////////////////////////
//
// The device's bit in the Device Reset/Enable registers.  Held is a reset.
//
//////////////////////////////////////////////////////////////////////////
void CHCP65Device::SetHeldInReset(bool bHeld)
{
	mbHeldInReset = bHeld;
	if (bHeld)
	{
		Reset();
	}
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CHCP65Device::IsHeldInReset(void)
{
	return mbHeldInReset;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CHCP65Device::CatchUp(uint64 uiCycle)
{
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
uint64 CHCP65Device::NextEvent(void)
{
	return HCP65_NEVER;
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
bool CHCP65Device::IsInterrupting(void)
{
	return false;
}
