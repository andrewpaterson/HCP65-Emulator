#include "HCP65.h"


//////////////////////////////////////////////////////////////////////////
//
// No flat memory block; every access goes to ReadByte and WriteByte.
//
//////////////////////////////////////////////////////////////////////////
void CHCP65::Init(void)
{
	mcMPU.Init(ReadByte, WriteByte, this, NULL, 0);
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CHCP65::Kill(void)
{
	mcMPU.Kill();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
void CHCP65::Reset(void)
{
	mcMPU.Reset();
}


//////////////////////////////////////////////////////////////////////////
//
//
//////////////////////////////////////////////////////////////////////////
CFast65C816* CHCP65::GetMPU(void)
{
	return &mcMPU;
}


//////////////////////////////////////////////////////////////////////////
//
// Nothing drives the data bus yet.
//
//////////////////////////////////////////////////////////////////////////
uint8 CHCP65::ReadByte(void* pvContext, uint32 uiAddress)
{
	return 0xFF;
}


//////////////////////////////////////////////////////////////////////////
//
// Nothing is listening yet.
//
//////////////////////////////////////////////////////////////////////////
void CHCP65::WriteByte(void* pvContext, uint32 uiAddress, uint8 uiValue)
{
}
